def plot_backtesting(y_true, y_pred, model_name, n_points=50):
    y_true_sample = np.array(y_true[:n_points])
    y_pred_sample = np.array(y_pred[:n_points])

    plt.figure(figsize=(12, 6))
    plt.plot(y_true_sample, label="Actual Demand")
    plt.plot(y_pred_sample, label="Predicted Demand")
    plt.xlabel("Test Sample Index")
    plt.ylabel("Units Sold")
    plt.title(f"{model_name}: Backtesting on Historical Data")
    plt.legend()
    plt.grid(True)
    plt.show()

