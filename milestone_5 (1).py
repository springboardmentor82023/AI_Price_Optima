def plot_model_metrics(y_true, xgb_pred, lgb_pred):
    xgb_mae = mean_absolute_error(y_true, xgb_pred)
    xgb_rmse = np.sqrt(mean_squared_error(y_true, xgb_pred))
    xgb_r2 = r2_score(y_true, xgb_pred)

    lgb_mae = mean_absolute_error(y_true, lgb_pred)
    lgb_rmse = np.sqrt(mean_squared_error(y_true, lgb_pred))
    lgb_r2 = r2_score(y_true, lgb_pred)

    metrics = ["MAE", "RMSE", "R2"]
    xgb_values = [xgb_mae, xgb_rmse, xgb_r2]
    lgb_values = [lgb_mae, lgb_rmse, lgb_r2]

    x = np.arange(len(metrics))
    width = 0.35

    plt.figure(figsize=(8, 6))
    plt.bar(x - width/2, xgb_values, width, label="XGBoost")
    plt.bar(x + width/2, lgb_values, width, label="LightGBM")
    plt.xticks(x, metrics)
    plt.ylabel("Score")
    plt.title("Model Performance Comparison")
    plt.legend()
    plt.grid(True, axis='y')
    plt.show()

